CREATE TABLE IF NOT EXISTS tenant_ai_usage_daily (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL CONSTRAINT fk_taud_tenant REFERENCES tenants(id) ON DELETE CASCADE,
    usage_date DATE NOT NULL,
    task_type VARCHAR(50) NOT NULL,
    provider VARCHAR(50) NOT NULL,
    model_name VARCHAR(100) NOT NULL,
    total_requests INT NOT NULL DEFAULT 0,
    failed_requests INT NOT NULL DEFAULT 0,
    total_prompt_tokens BIGINT NOT NULL DEFAULT 0,
    total_completion_tokens BIGINT NOT NULL DEFAULT 0,
    estimated_cost_usd DECIMAL(12, 6) NOT NULL DEFAULT 0.000000,
    total_latency_ms BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_tenant_ai_usage_daily_dim UNIQUE (tenant_id, usage_date, task_type, provider, model_name)
);

CREATE INDEX IF NOT EXISTS idx_taud_tenant_date ON tenant_ai_usage_daily(tenant_id, usage_date);
CREATE INDEX IF NOT EXISTS idx_taud_usage_date ON tenant_ai_usage_daily(usage_date);
