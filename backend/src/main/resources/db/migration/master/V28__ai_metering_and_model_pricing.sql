CREATE TABLE IF NOT EXISTS ai_model_pricings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(50) NOT NULL,
    model_name VARCHAR(100) NOT NULL,
    input_price_per_1m_tokens DECIMAL(12, 4) NOT NULL DEFAULT 0.0000,
    output_price_per_1m_tokens DECIMAL(12, 4) NOT NULL DEFAULT 0.0000,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_model_pricings_provider_model UNIQUE (provider, model_name)
);

CREATE INDEX IF NOT EXISTS idx_ai_model_pricings_provider ON ai_model_pricings(provider);

