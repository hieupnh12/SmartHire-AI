-- V39: Replace platform_audit_logs with tenant_system_logs (System & Application Logs per Tenant)

-- 1. Drop old platform_audit_logs if exists
DROP TABLE IF EXISTS platform_audit_logs CASCADE;

-- 2. Create tenant_system_logs
CREATE TABLE IF NOT EXISTS tenant_system_logs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_code         VARCHAR(64) NOT NULL DEFAULT 'SYSTEM',
    level               VARCHAR(16) NOT NULL DEFAULT 'ERROR',
    category            VARCHAR(64) NOT NULL DEFAULT 'APPLICATION',
    action              VARCHAR(64) NOT NULL,
    message             TEXT NOT NULL,
    endpoint            VARCHAR(255) NULL,
    method              VARCHAR(16) NULL,
    status_code         INT NULL,
    ip_address          VARCHAR(64) NULL,
    trace_id            VARCHAR(64) NULL,
    stack_trace         TEXT NULL,
    metadata_json       JSONB NULL,
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_tsl_tenant_code ON tenant_system_logs(tenant_code);
CREATE INDEX IF NOT EXISTS idx_tsl_level ON tenant_system_logs(level);
CREATE INDEX IF NOT EXISTS idx_tsl_created_at ON tenant_system_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_tsl_tenant_created ON tenant_system_logs(tenant_code, created_at DESC);
